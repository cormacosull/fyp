# Function to parse phoneme timing
def parse_phoneme_timing(data):
    result = []
    for word in data.get('timing', []):
        for phone in word.get('phones', []):
            symbol = phone.get('symbol')
            result.append({
                'symbol': symbol,
                'end': phone.get('end'),
                'viseme': ABAIR_PHONEME_TO_VISEME.get(symbol, 'mouthOpen')
            })
    return result

# Function to convert Rhubarb JSON to visemes
def convert_to_visemes(rhubarb_json):
    visemes = []
    for cue in rhubarb_json.get("mouthCues", []):
        visemes.append({
            "start": cue["start"],
            "end": cue["end"],
            "viseme": RHUBARB_TO_OCULUS.get(cue["value"], "sil")
        })
    return visemes

